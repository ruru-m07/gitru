async function loadVSCodeTheme(monaco: Monaco) {
  // Load the actual Vesper theme JSON (exported from VS Code)
  const vesperTheme = await fetch("/vesper-theme.json").then((r) => r.json());

  // Convert and register
  monaco.editor.defineTheme("vesper", {
    base: "vs-dark",
    inherit: true,
    colors: vesperTheme.colors,
    rules: convertTokenColors(vesperTheme.tokenColors),
  });
}

function convertTokenColors(tokenColors: any[]) {
  return tokenColors.flatMap((entry) => {
    const scopes = Array.isArray(entry.scope) ? entry.scope : [entry.scope];
    return scopes.map((scope) => ({
      token: scope,
      foreground: entry.settings.foreground?.replace("#", ""),
      background: entry.settings.background?.replace("#", ""),
      fontStyle: entry.settings.fontStyle,
    }));
  });
}
