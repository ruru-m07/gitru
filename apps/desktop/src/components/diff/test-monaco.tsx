const tokenColorsToRules = (
  tokenColors: typeof vesperTokenColors,
): { token: string; foreground?: string; fontStyle?: string }[] => {
  const rules: Map<string, { foreground?: string; fontStyle?: string }> =
    new Map();

  tokenColors.forEach((entry) => {
    const scopes = Array.isArray(entry.scope) ? entry.scope : [entry.scope];
    const foreground = entry.settings.foreground
      ? entry.settings.foreground.replace("#", "").toLowerCase()
      : undefined;
    const fontStyle = entry.settings.fontStyle;

    scopes.forEach((scope) => {
      // Map common TextMate scopes to Monaco tokens
      const monacoMappings: Record<string, string[]> = {
        comment: ["comment"],
        string: ["string"],
        keyword: ["keyword"],
        variable: ["variable", "identifier"], // ✅ Key fix
        "variable.language": ["variable.predefined"],
        "variable.parameter": ["variable.parameter"],
        "variable.other": ["variable.other"],
        "entity.name.function": ["identifier.function", "function"],
        "entity.name.type": ["type", "type.identifier"],
        "entity.name.tag": ["tag"],
        "constant.numeric": ["number"],
        "constant.language.boolean": ["keyword.boolean"],
        "storage.type": ["keyword.type"],
        "support.type": ["type"],
        "support.class": ["type.class"],
        "support.function": ["support.function"],
      };

      // Check for exact match first
      const tokens = monacoMappings[scope] || [scope];

      tokens.forEach((token) => {
        if (!rules.has(token)) {
          rules.set(token, { foreground, fontStyle });
        }
      });

      // Also add the full scope as-is (Monaco might support it)
      if (!rules.has(scope)) {
        rules.set(scope, { foreground, fontStyle });
      }
    });
  });

  return Array.from(rules.entries()).map(([token, settings]) => ({
    token,
    ...settings,
  }));
};

